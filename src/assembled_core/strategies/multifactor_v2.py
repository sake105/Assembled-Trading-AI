def compute_signals(
    prices_with_features: pd.DataFrame,
    strategy_cfg: dict[str, Any] | None = None,
) -> pd.DataFrame:
    """Generate 30-factor signals with regime-conditional weights.

    All 30 factors are actively computed. Factors degrade gracefully to 0.0
    when external data is unavailable. Dead factors (zero variance) are
    excluded from the weighted composite to prevent dilution.

    Drop-in replacement for v1. Same input/output schema.
    """
    cfg = strategy_cfg or {}
    min_score = float(cfg.get("min_signal_score", 0.0))
    ema_fast = int(cfg.get("ema_fast") or 20)
    ema_slow = int(cfg.get("ema_slow") or 60)

    if prices_with_features.empty or "symbol" not in prices_with_features.columns:
        return _empty_signals()

    df = prices_with_features.copy()
    if "timestamp" not in df.columns:
        return _empty_signals()

    # Latest bar per symbol
    latest = (
        df.sort_values("timestamp").groupby("symbol", group_keys=False).tail(1).copy()
    )
    if latest.empty:
        return _empty_signals()

    latest_symbols = latest["symbol"].tolist()
    # Bar date: use latest timestamp in the panel as PIT anchor for altdata lookups.
    # This prevents Timestamp.now() look-ahead in backtest mode (factors 19-24, 33).
    _bar_as_of = pd.Timestamp(latest["timestamp"].max())

    # --- Detect regime ---
    regime_label = _detect_regime(df, cfg)
    weights = _get_weights_for_regime(regime_label, cfg)

    # --- Signal decay gate (policy-gated, shadow mode by default) ---
    from src.assembled_core.strategies.signal_decay_gate import (
        apply_multipliers as _apply_decay,
    )

    _decay_cfg = cfg.get("signal_decay", {}) or {}
    weights, _decay_multipliers = _apply_decay(
        dict(weights),
        enabled=bool(_decay_cfg.get("enabled", False)),
        stale_multiplier=float(_decay_cfg.get("stale_multiplier", 0.0)),
        report_path=(
            None
            if _decay_cfg.get("report_path") is None
            else __import__("pathlib").Path(_decay_cfg["report_path"])
        ),
    )

    logger.info(
        "[MF-V2] Regime=%s, %d weight entries, universe=%d symbols",
        regime_label,
        len(weights),
        len(latest_symbols),
    )

    # --- Compute raw factor values (factors 1-15 from v1) ---
    scores = pd.DataFrame({"symbol": latest["symbol"].values})
    scores.index = latest.index

    close = pd.to_numeric(latest.get("close", pd.Series(dtype=float)), errors="coerce")

    # Factors 1-4: Trend
    scores["trend_ema_spread"] = _compute_ema_spread(df, ema_fast, ema_slow)
    scores["trend_ma200_position"] = _ma_position(
        latest, close, "ta_ma_200_v1", fallback_window=200
    )
    scores["trend_adx_strength"] = _safe_col(latest, "ta_adx_v1", default=0.0) / 100.0
    scores["trend_macd_hist"] = _safe_col(latest, "ta_macd_hist_v1", default=0.0)

    # Factors 5-7: Momentum
    scores["mom_rsi_centered"] = _rsi_score(latest)
    scores["mom_volume_weighted"] = _safe_col(
        latest, "ta_vol_weighted_mom_20d_v1", default=0.0
    )
    scores["mom_obv_trend"] = _obv_trend(df)

    # Factors 8-9: Mean-reversion guard
    scores["mr_bollinger_pctb"] = _bollinger_score(latest)
    scores["mr_stoch_oversold"] = _stochastic_score(latest)

    # Factors 10-11: Volume
    scores["vol_abnormal"] = _abnormal_volume_score(latest)
    scores["vol_tick_imbalance"] = _safe_col(latest, "tick_imbalance_20d", default=0.5)

    # Factors 12-13: Volatility
    scores["vola_regime_score"] = _volatility_regime_score(latest)
    scores["vola_vov_penalty"] = _vov_penalty(latest)

    # Factors 14-15: Breadth (two genuinely different signals)
    scores["breadth_above_ma"] = _compute_breadth_score(df)
    scores["breadth_ad_line"] = _compute_breadth_ad_slope(df)

    # --- New v2 factors (16-29) — defensive, all return NaN on failure ---

    # Factors 16-17: Mean-reversion from sidecar module
    mr_16 = _compute_mr_zscore_reversal_3d(df)
    mr_17 = _compute_mr_rsi_extreme_uptrend(df)
    scores["mr_zscore_reversal_3d"] = (
        scores["symbol"].map(mr_16).fillna(0.0) if not mr_16.empty else 0.0
    )
    scores["mr_rsi_extreme_uptrend"] = (
        scores["symbol"].map(mr_17).fillna(0.0) if not mr_17.empty else 0.0
    )

    # Factor 18: Sector rotation
    sector_bias = _compute_sector_rotation_bias(df, latest_symbols, cfg)
    scores["sector_rotation_bias"] = (
        scores["symbol"].map(sector_bias).fillna(0.0) if not sector_bias.empty else 0.0
    )

    # Factors 19-20: Earnings + Insider
    earn_z, insider_z = _compute_earnings_insider_factors(
        latest_symbols, cfg, as_of=_bar_as_of
    )
    scores["earnings_surprise_z"] = (
        scores["symbol"].map(earn_z).fillna(0.0) if not earn_z.empty else 0.0
    )
    scores["insider_activity_score"] = (
        scores["symbol"].map(insider_z).fillna(0.0) if not insider_z.empty else 0.0
    )

    # Factors 21-24: News + Macro
    news_macro = _compute_news_macro_factors(latest_symbols, cfg, as_of=_bar_as_of)
    scores["news_sentiment_7d"] = (
        scores["symbol"]
        .map(news_macro.get("news_sentiment_7d_z", pd.Series(dtype=float)))
        .fillna(0.0)
        if "news_sentiment_7d_z" in news_macro
        else 0.0
    )
    scores["news_volume_spike"] = (
        scores["symbol"]
        .map(news_macro.get("news_volume_spike_z", pd.Series(dtype=float)))
        .fillna(0.0)
        if "news_volume_spike_z" in news_macro
        else 0.0
    )
    scores["macro_growth_momentum"] = (
        scores["symbol"]
        .map(news_macro.get("macro_growth_momentum_z", pd.Series(dtype=float)))
        .fillna(0.0)
        if "macro_growth_momentum_z" in news_macro
        else 0.0
    )
    scores["macro_inflation_surprise"] = (
        scores["symbol"]
        .map(news_macro.get("macro_inflation_surprise_z", pd.Series(dtype=float)))
        .fillna(0.0)
        if "macro_inflation_surprise_z" in news_macro
        else 0.0
    )

    # Factors 25-27: Intermarket (bond-equity, credit spread, yield curve)
    intermarket = _compute_intermarket_factors(latest_symbols, latest)
    scores["intermarket_bond_equity"] = (
        scores["symbol"]
        .map(intermarket.get("intermarket_bond_equity", pd.Series(dtype=float)))
        .fillna(0.0)
        if "intermarket_bond_equity" in intermarket
        else 0.0
    )
    scores["intermarket_credit_spread"] = (
        scores["symbol"]
        .map(intermarket.get("intermarket_credit_spread", pd.Series(dtype=float)))
        .fillna(0.0)
        if "intermarket_credit_spread" in intermarket
        else 0.0
    )
    scores["intermarket_yield_curve"] = (
        scores["symbol"]
        .map(intermarket.get("intermarket_yield_curve", pd.Series(dtype=float)))
        .fillna(0.0)
        if "intermarket_yield_curve" in intermarket
        else 0.0
    )

    # Factors 28-29: Options (put-call extreme, VIX regime score)
    options = _compute_options_factors(latest_symbols, latest)
    scores["options_put_call_extreme"] = (
        scores["symbol"]
        .map(options.get("options_put_call_extreme", pd.Series(dtype=float)))
        .fillna(0.0)
        if "options_put_call_extreme" in options
        else 0.0
    )
    scores["vix_regime_score"] = (
        scores["symbol"]
        .map(options.get("vix_regime_score", pd.Series(dtype=float)))
        .fillna(0.0)
        if "vix_regime_score" in options
        else 0.0
    )

    # Factor 30: Congress trading activity
    congress = _compute_congress_factors(latest_symbols, latest)
    scores["congress_activity"] = (
        scores["symbol"]
        .map(congress.get("congress_activity", pd.Series(dtype=float)))
        .fillna(0.0)
        if "congress_activity" in congress
        else 0.0
    )

    # Factor 31: Geo-political risk composite (Pfad B). F-B-1: pass as_of.
    geo = _compute_geo_risk_composite(latest_symbols, latest, as_of=_bar_as_of)
    scores["geo_risk_composite"] = (
        scores["symbol"]
        .map(geo.get("geo_risk_composite", pd.Series(dtype=float)))
        .fillna(0.0)
        if "geo_risk_composite" in geo
        else 0.0
    )

    # Factor 32: Insider cluster buy/sell (Cohen et al. 2012, +2-4% p.a. alpha). F-B-2: pass as_of.
    insider_cl = _compute_insider_cluster_factor(
        latest_symbols, latest, as_of=_bar_as_of
    )
    scores["insider_cluster_score"] = (
        scores["symbol"]
        .map(insider_cl.get("insider_cluster_score", pd.Series(dtype=float)))
        .fillna(0.0)
        if "insider_cluster_score" in insider_cl
        else 0.0
    )

    # Factor 33: PEAD/SUE — post-earnings drift (Bernard & Thomas 1989)
    pead = _compute_pead_sue_factor(latest_symbols, latest, as_of=_bar_as_of)
    scores["pead_sue_score"] = (
        scores["symbol"]
        .map(pead.get("pead_sue_score", pd.Series(dtype=float)))
        .fillna(0.0)
        if "pead_sue_score" in pead
        else 0.0
    )

    # Factor 34: Buyback drift (Ikenberry et al., 60-90d post-announcement). F-B-3: pass as_of.
    buyback = _compute_buyback_drift_factor(latest_symbols, latest, as_of=_bar_as_of)
    scores["buyback_drift_score"] = (
        scores["symbol"]
        .map(buyback.get("buyback_drift_score", pd.Series(dtype=float)))
        .fillna(0.0)
        if "buyback_drift_score" in buyback
        else 0.0
    )

    # Factor 35 (Item 106): Options IV-skew — institutional hedging signal.
    # Zero-weighted in composite by default; available as ML feature.
    opts_iv = _compute_options_iv_factor(latest_symbols, latest)
    scores["options_iv_skew_score"] = (
        scores["symbol"]
        .map(opts_iv.get("options_iv_skew_score", pd.Series(dtype=float)))
        .fillna(0.0)
        if "options_iv_skew_score" in opts_iv
        else 0.0
    )

    # Crash probability inverse -- not z-scored (scalar → zero variance).
    # Applied as multiplier post-composite via _crash_prediction_multiplier.

    # --- Cross-sectional z-score per factor (vectorized across all columns) ---
    # Use ddof=0 (population std) to avoid NaN for single-row universes.
    # For very small universes (< SMALL_UNIVERSE_THRESHOLD symbols), z-scoring
    # is statistically meaningless, so use rank-normalization instead.
    factor_cols = [c for c in scores.columns if c != "symbol"]
    n_rows = len(scores)
    # Item 48: fillna(0.0) BEFORE clip — missing factors treated as neutral (0).
    # This prevents NaN from propagating through rank/z-score into the composite.
    factor_df = scores[factor_cols].astype(float).fillna(0.0)
    if n_rows < SMALL_UNIVERSE_THRESHOLD:
        ranks = factor_df.rank(method="average", na_option="bottom")
        scores[factor_cols] = (((ranks / max(n_rows, 1)) - 0.5) * RANK_NORM_SCALE).clip(
            FACTOR_CLIP_MIN, FACTOR_CLIP_MAX
        )
    else:
        means = factor_df.mean()
        stds = factor_df.std(ddof=0)
        # Divide by std; set to NaN where std ≈ 0 (zero-variance factor), then
        # fill NaN → 0.0.  Avoid .where(valid, 0.0) with a column-indexed
        # boolean Series: pandas 2.x aligns it against the row index, not the
        # column axis, silently zeroing every cell.
        safe_stds = stds.replace(0.0, np.nan).where(
            stds > STD_ZERO_REPLACE, other=np.nan
        )
        normalized = (factor_df - means) / safe_stds
        # fillna(0.0): zero-variance factors and any residual NaN → neutral
        scores[factor_cols] = normalized.fillna(0.0).clip(
            FACTOR_CLIP_MIN, FACTOR_CLIP_MAX
        )

    # --- Weighted composite with regime-conditional weights ---
    # Fix 20: Only count factors that contributed non-zero values to avoid
    # dead factors diluting the composite via their weight in total_weight.
    # Item 47: Use safe_divide for the total_weight normalisation to guard
    # against the edge case where every factor is zero-variance.
    composite = pd.Series(0.0, index=scores.index)
    total_weight = 0.0
    used_factors = []
    for factor_name, weight in weights.items():
        if factor_name in scores.columns:
            factor_vals = scores[factor_name].fillna(0.0)
            if factor_vals.abs().sum() > FACTOR_ZERO_VARIANCE_EPS:
                composite += weight * factor_vals
                total_weight += weight
                used_factors.append(factor_name)

    # safe_divide: if no live factors (all zero-variance), composite stays 0.0
    composite = composite * safe_divide(1.0, total_weight, default=0.0)

    # --- Regime + crash exposure multiplier ---
    # crash_probability is applied ONLY via _crash_prediction_multiplier as a
    # risk-overlay exposure scaler (0.0–1.0). No separate additive/scaler
    # application — that would double-count.
    #
    regime_mult = REGIME_EXPOSURE.get(regime_label, 0.70)
    crash_mult = _crash_prediction_multiplier(df, cfg)
    exposure_mult = regime_mult * crash_mult

    # VIX hard cap — overrides regime/crash multiplier during vol spikes
    if "vix" in latest.columns:
        _vix_vals = latest["vix"].dropna()
        if len(_vix_vals) > 0:
            _vix_val = float(_vix_vals.median())
            # Tiered VIX cap: 4-tier coverage from moderate to extreme vol regimes
            # Thresholds from multifactor_v2_constants (calibrated vs stress tests)
            if _vix_val > VIX_THRESHOLD_EXTREME:
                _vix_cap = VIX_CAP_EXTREME  # extreme panic (GFC/COVID peak)
            elif _vix_val > VIX_THRESHOLD_CRISIS:
                _vix_cap = VIX_CAP_CRISIS  # crisis (GFC, COVID March)
            elif _vix_val > VIX_THRESHOLD_ELEVATED:
                _vix_cap = VIX_CAP_ELEVATED  # elevated stress (2022 inflation)
            elif _vix_val >= VIX_THRESHOLD_MILD:
                _vix_cap = VIX_CAP_MILD  # mild caution
            else:
                _vix_cap = 1.0
            if _vix_cap < exposure_mult:
                logger.info(
                    "[MF-V2] VIX=%.1f → exposure capped %.2f→%.2f",
                    _vix_val,
                    exposure_mult,
                    _vix_cap,
                )
                exposure_mult = _vix_cap

    # Yield-curve inversion cap — protects against slow stagflation bleeding
    # (VIX-cap alone misses low-VIX bear markets like 2022)
    if "yield_curve_slope" in latest.columns:
        _yc_vals = pd.to_numeric(latest["yield_curve_slope"], errors="coerce").dropna()
        if len(_yc_vals) > 0 and float(_yc_vals.median()) < 0:
            # Confirm persistence: require YIELD_CURVE_INVERSION_FRACTION of
            # last YIELD_CURVE_LOOKBACK_DAYS trading dates inverted
            _yc_persistent = False
            if "yield_curve_slope" in df.columns:
                _yc_hist = df.sort_values("timestamp").drop_duplicates(
                    "timestamp", keep="last"
                )
                _yc_recent = pd.to_numeric(
                    _yc_hist["yield_curve_slope"].tail(YIELD_CURVE_LOOKBACK_DAYS),
                    errors="coerce",
                ).dropna()
                if len(_yc_recent) >= YIELD_CURVE_INVERSION_MIN_HISTORY and (
                    _yc_recent < 0
                ).sum() >= min(20, len(_yc_recent) * YIELD_CURVE_INVERSION_FRACTION):
                    _yc_persistent = True
            else:
                _yc_persistent = (
                    False  # no panel history → cannot confirm persistence; skip cap
                )
            if _yc_persistent:
                _yc_cap = float(
                    cfg.get("yield_curve_inversion_cap", YIELD_CURVE_CAP_DEFAULT)
                )
                if _yc_cap < exposure_mult:
                    logger.info(
                        "[MF-V2] Yield-curve inverted (persistent) → exposure capped %.2f→%.2f",
                        exposure_mult,
                        _yc_cap,
                    )
                    exposure_mult = _yc_cap

    # Drawdown self-damper — halves exposure for 30 days after MDD > 12%
    with _DD_LOCK:
        if _DD_DAMPER["damper_active"]:
            _damp = float(_DD_DAMPER["damper_factor"])
            if _damp < 1.0:
                logger.info(
                    "[MF-V2] DD damper active → exposure scaled ×%.2f (until %s)",
                    _damp,
                    _DD_DAMPER["damper_until"],
                )
                exposure_mult = exposure_mult * _damp

    composite = composite * exposure_mult

    # --- Build output signals ---
    composite_arr = composite.to_numpy(dtype=float)
    ema_spread_arr = (
        scores["trend_ema_spread"].to_numpy(dtype=float)
        if "trend_ema_spread" in scores.columns
        else np.zeros(len(composite_arr))
    )
    sym_list = latest["symbol"].tolist()
    ts_list = (
        latest["timestamp"].tolist()
        if "timestamp" in latest.columns
        else [None] * len(latest)
    )
    scores_mat = scores[factor_cols].to_numpy(dtype=float)
    col_idx = {f: j for j, f in enumerate(factor_cols)}

    out = []
    for i in range(len(latest)):
        score = composite_arr[i]
        ema_spread = ema_spread_arr[i]
        if score > min_score and ema_spread > -0.5:
            row_scores = scores_mat[i]
            # Top contributing factors for reason string
            factor_contribs = [
                (f, float(row_scores[col_idx[f]]) * weights.get(f, 0.0))
                for f in used_factors
                if f in col_idx
            ]
            factor_contribs.sort(key=lambda x: abs(x[1]), reverse=True)
            reasons = [f"{f}={v:.2f}" for f, v in factor_contribs[:5]]

            out.append(
                {
                    "timestamp": ts_list[i],
                    "symbol": sym_list[i],
                    "direction": "LONG",
                    "score": float(score),
                    "reason": f"v2|regime={regime_label}|" + "; ".join(reasons),
                    # Preserve factor scores for meta-model
                    **{
                        f: float(row_scores[col_idx[f]])
                        for f in factor_cols
                        if f in col_idx
                    },
                }
            )

    if not out:
        return _empty_signals()

    result = pd.DataFrame(out).sort_values("score", ascending=False)

    # --- Meta-model confidence filter (opt-in) ---
    meta_cfg = cfg.get("meta_model") or {}
    if meta_cfg.get("enabled", False):
        try:
            result = _apply_meta_model_filter(result, meta_cfg)
        except Exception as exc:
            logger.debug("[MF-V2] meta_model filter skipped: %s", exc)

    logger.info(
        "[MF-V2] %d LONG signals from %d symbols "
        "(regime=%s, exposure=%.2f, crash_mult=%.3f, active_factors=%d/%d)",
        len(result),
        len(latest),
        regime_label,
        exposure_mult,
        crash_mult,
        len(used_factors),
        len(weights),
    )
    return result


def _apply_meta_model_filter(
    signals: pd.DataFrame,
    meta_cfg: dict[str, Any],
) -> pd.DataFrame:
    """Load classifier, compute confidence, filter / scale signals."""
    model_path = meta_cfg.get("model_path")
    if not model_path or not Path(model_path).exists():
        raise FileNotFoundError(f"meta_model path missing: {model_path}")

    min_conf = float(meta_cfg.get("min_confidence", 0.55))

    import joblib

    try:
        model = joblib.load(model_path)
    except (EOFError, Exception) as exc:
        raise RuntimeError(
            f"[multifactor_v2] Failed to load meta-model from {model_path}: {exc}"
        ) from exc

    feature_cols = meta_cfg.get("feature_cols")
    if not feature_cols:
        feature_cols = [
            c
            for c in signals.columns
            if c.startswith(
                (
                    "trend_",
                    "mom_",
                    "mr_",
                    "vol_",
                    "vola_",
                    "breadth_",
                    "sector_",
                    "earnings_",
                    "insider_",
                    "news_",
                    "macro_",
                    "intermarket_",
                    "options_",
                    "vix_",
                    "crash_",
                )
            )
        ]
    if not feature_cols:
        raise ValueError("meta_model: no feature columns available")

    missing = [c for c in feature_cols if c not in signals.columns]
    if missing:
        raise ValueError(f"meta_model: missing columns: {missing}")

    # Guard against silent feature poisoning: fillna(0.0) treats a data-feed
    # gap as a real standardized value, drifting confidence without warning.
    # Predict only on rows with complete features; rows with any NaN feature
    # get meta_confidence=NaN and are filtered by the min_conf gate below.
    feat_frame = signals[feature_cols]
    complete_mask = feat_frame.notna().all(axis=1).to_numpy()
    n_nan_rows = int((~complete_mask).sum())
    if n_nan_rows > 0:
        logger.warning(
            "[multifactor_v2.meta_model] %d/%d rows skipped due to NaN features",
            n_nan_rows,
            len(signals),
        )

    confidence = np.full(len(signals), np.nan, dtype=float)
    if complete_mask.any():
        X = feat_frame.loc[complete_mask].to_numpy()
        proba = model.predict_proba(X)
        if proba.ndim != 2 or proba.shape[1] < 2:
            raise ValueError(f"meta_model: unexpected shape {proba.shape}")
        confidence[complete_mask] = proba[:, 1]

    out = signals.copy()
    out["meta_confidence"] = confidence
    out = out.loc[np.nan_to_num(confidence, nan=-1.0) >= min_conf].copy()
    if out.empty:
        return out
    if "score" in out.columns:
        out["score"] = out["score"].astype(float) * out["meta_confidence"].astype(float)
    return out.reset_index(drop=True)


