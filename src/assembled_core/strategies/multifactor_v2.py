def compute_signals(
    prices_with_features: pd.DataFrame,
    strategy_cfg: dict[str, Any] | None = None,
) -> pd.DataFrame:
    """Generate 30-factor signals with regime-conditional weights.

    All 30 factors are actively computed. Factors degrade gracefully to 0.0
    when external data is unavailable. Dead factors (zero variance) are
    excluded from the weighted composite to prevent dilution.

    Drop-in replacement for v1. Same input/output schema.
    """
    cfg = strategy_cfg or {}
    min_score = float(cfg.get("min_signal_score", 0.0))
    ema_fast = int(cfg.get("ema_fast", 20))
    ema_slow = int(cfg.get("ema_slow", 60))

    if prices_with_features.empty or "symbol" not in prices_with_features.columns:
        return _empty_signals()

    df = prices_with_features.copy()
    if "timestamp" not in df.columns:
        return _empty_signals()

    # Latest bar per symbol
    latest = (
        df.sort_values("timestamp")
        .groupby("symbol", group_keys=False)
        .tail(1)
        .copy()
    )
    if latest.empty:
        return _empty_signals()

    latest_symbols = latest["symbol"].tolist()

    # --- Detect regime ---
    regime_label = _detect_regime(df, cfg)
    weights = _get_weights_for_regime(regime_label, cfg)
    logger.info(
        "[MF-V2] Regime=%s, %d weight entries, universe=%d symbols",
        regime_label, len(weights), len(latest_symbols),
    )

    # --- Compute raw factor values (factors 1-15 from v1) ---
    scores = pd.DataFrame({"symbol": latest["symbol"].values})
    scores.index = latest.index

    close = pd.to_numeric(latest.get("close", pd.Series(dtype=float)), errors="coerce")

    # Factors 1-4: Trend
    scores["trend_ema_spread"] = _compute_ema_spread(df, ema_fast, ema_slow)
    scores["trend_ma200_position"] = _ma_position(latest, close, "ta_ma_200_v1", fallback_window=200)
    scores["trend_adx_strength"] = _safe_col(latest, "ta_adx_v1", default=0.0) / 100.0
    scores["trend_macd_hist"] = _safe_col(latest, "ta_macd_hist_v1", default=0.0)

    # Factors 5-7: Momentum
    scores["mom_rsi_centered"] = _rsi_score(latest)
    scores["mom_volume_weighted"] = _safe_col(latest, "ta_vol_weighted_mom_20d_v1", default=0.0)
    scores["mom_obv_trend"] = _obv_trend(df)

    # Factors 8-9: Mean-reversion guard
    scores["mr_bollinger_pctb"] = _bollinger_score(latest)
    scores["mr_stoch_oversold"] = _stochastic_score(latest)

    # Factors 10-11: Volume
    scores["vol_abnormal"] = _abnormal_volume_score(latest)
    scores["vol_tick_imbalance"] = _safe_col(latest, "tick_imbalance_20d", default=0.5)

    # Factors 12-13: Volatility
    scores["vola_regime_score"] = _volatility_regime_score(latest)
    scores["vola_vov_penalty"] = _vov_penalty(latest)

    # Factors 14-15: Breadth (two genuinely different signals)
    scores["breadth_above_ma"] = _compute_breadth_score(df)
    scores["breadth_ad_line"] = _compute_breadth_ad_slope(df)

    # --- New v2 factors (16-29) — defensive, all return NaN on failure ---

    # Factors 16-17: Mean-reversion from sidecar module
    mr_16 = _compute_mr_zscore_reversal_3d(df)
    mr_17 = _compute_mr_rsi_extreme_uptrend(df)
    scores["mr_zscore_reversal_3d"] = scores["symbol"].map(mr_16).fillna(0.0) if not mr_16.empty else 0.0
    scores["mr_rsi_extreme_uptrend"] = scores["symbol"].map(mr_17).fillna(0.0) if not mr_17.empty else 0.0

    # Factor 18: Sector rotation
    sector_bias = _compute_sector_rotation_bias(df, latest_symbols, cfg)
    scores["sector_rotation_bias"] = scores["symbol"].map(sector_bias).fillna(0.0) if not sector_bias.empty else 0.0

    # Factors 19-20: Earnings + Insider
    earn_z, insider_z = _compute_earnings_insider_factors(latest_symbols, cfg)
    scores["earnings_surprise_z"] = scores["symbol"].map(earn_z).fillna(0.0) if not earn_z.empty else 0.0
    scores["insider_activity_score"] = scores["symbol"].map(insider_z).fillna(0.0) if not insider_z.empty else 0.0

    # Factors 21-24: News + Macro
    news_macro = _compute_news_macro_factors(latest_symbols, cfg)
    scores["news_sentiment_7d"] = scores["symbol"].map(
        news_macro.get("news_sentiment_7d_z", pd.Series(dtype=float))
    ).fillna(0.0) if "news_sentiment_7d_z" in news_macro else 0.0
    scores["news_volume_spike"] = scores["symbol"].map(
        news_macro.get("news_volume_spike_z", pd.Series(dtype=float))
    ).fillna(0.0) if "news_volume_spike_z" in news_macro else 0.0
    scores["macro_growth_momentum"] = scores["symbol"].map(
        news_macro.get("macro_growth_momentum_z", pd.Series(dtype=float))
    ).fillna(0.0) if "macro_growth_momentum_z" in news_macro else 0.0
    scores["macro_inflation_surprise"] = scores["symbol"].map(
        news_macro.get("macro_inflation_surprise_z", pd.Series(dtype=float))
    ).fillna(0.0) if "macro_inflation_surprise_z" in news_macro else 0.0

    # Factors 25-27: Intermarket (bond-equity, credit spread, yield curve)
    intermarket = _compute_intermarket_factors(latest_symbols, latest)
    scores["intermarket_bond_equity"] = scores["symbol"].map(
        intermarket.get("intermarket_bond_equity", pd.Series(dtype=float))
    ).fillna(0.0) if "intermarket_bond_equity" in intermarket else 0.0
    scores["intermarket_credit_spread"] = scores["symbol"].map(
        intermarket.get("intermarket_credit_spread", pd.Series(dtype=float))
    ).fillna(0.0) if "intermarket_credit_spread" in intermarket else 0.0
    scores["intermarket_yield_curve"] = scores["symbol"].map(
        intermarket.get("intermarket_yield_curve", pd.Series(dtype=float))
    ).fillna(0.0) if "intermarket_yield_curve" in intermarket else 0.0

    # Factors 28-29: Options (put-call extreme, VIX regime score)
    options = _compute_options_factors(latest_symbols, latest)
    scores["options_put_call_extreme"] = scores["symbol"].map(
        options.get("options_put_call_extreme", pd.Series(dtype=float))
    ).fillna(0.0) if "options_put_call_extreme" in options else 0.0
    scores["vix_regime_score"] = scores["symbol"].map(
        options.get("vix_regime_score", pd.Series(dtype=float))
    ).fillna(0.0) if "vix_regime_score" in options else 0.0

    # Factor 30: Congress trading activity
    congress = _compute_congress_factors(latest_symbols, latest)
    scores["congress_activity"] = scores["symbol"].map(
        congress.get("congress_activity", pd.Series(dtype=float))
    ).fillna(0.0) if "congress_activity" in congress else 0.0

    # Crash probability inverse -- not z-scored (scalar → zero variance).
    # Applied as multiplier post-composite via _crash_prediction_multiplier.

    # --- Cross-sectional z-score per factor ---
    # Use ddof=0 (population std) to avoid NaN for single-row universes.
    # For very small universes (< 5 symbols), z-scoring is statistically
    # meaningless, so use rank-normalization instead.
    factor_cols = [c for c in scores.columns if c != "symbol"]
    n_rows = len(scores)
    for col in factor_cols:
        vals = scores[col].astype(float)
        if n_rows < 5:
            # Rank-normalize: rank / N, centered around 0
            ranks = vals.rank(method="average", na_option="bottom")
            scores[col] = ((ranks / max(n_rows, 1)) - 0.5) * 2.0
        else:
            mean_v = vals.mean()
            std_v = vals.std(ddof=0)
            if std_v > 1e-10:
                scores[col] = (vals - mean_v) / std_v
            else:
                scores[col] = 0.0
        scores[col] = scores[col].clip(-3.0, 3.0)

    # --- Weighted composite with regime-conditional weights ---
    # Fix 20: Only count factors that contributed non-zero values to avoid
    # dead factors diluting the composite via their weight in total_weight.
    composite = pd.Series(0.0, index=scores.index)
    total_weight = 0.0
    used_factors = []
    for factor_name, weight in weights.items():
        if factor_name in scores.columns:
            factor_vals = scores[factor_name].fillna(0.0)
            if factor_vals.abs().sum() > 1e-10:
                composite += weight * factor_vals
                total_weight += weight
                used_factors.append(factor_name)

    if total_weight > 0:
        composite = composite / total_weight

    # --- Regime + crash exposure multiplier ---
    # crash_probability is applied ONLY via _crash_prediction_multiplier as a
    # risk-overlay exposure scaler (0.0–1.0). No separate additive/scaler
    # application — that would double-count.
    #
    regime_mult = REGIME_EXPOSURE.get(regime_label, 0.70)
    crash_mult = _crash_prediction_multiplier(df, cfg)
    exposure_mult = regime_mult * crash_mult
    composite = composite * exposure_mult

    # --- Build output signals ---
    out = []
    for i, (idx, row) in enumerate(latest.iterrows()):
        sym = row["symbol"]
        score = float(composite.iloc[i]) if i < len(composite) else 0.0
        ts = row.get("timestamp")
        ema_spread = float(scores.iloc[i].get("trend_ema_spread", 0.0)) if i < len(scores) else 0.0

        if score > min_score and ema_spread > -0.5:
            # Top contributing factors for reason string
            factor_contribs = []
            for f in used_factors:
                fval = float(scores.iloc[i].get(f, 0.0))
                fw = weights.get(f, 0.0)
                factor_contribs.append((f, fval * fw))
            factor_contribs.sort(key=lambda x: abs(x[1]), reverse=True)
            reasons = [f"{f}={v:.2f}" for f, v in factor_contribs[:5]]

            out.append({
                "timestamp": ts,
                "symbol": sym,
                "direction": "LONG",
                "score": score,
                "reason": f"v2|regime={regime_label}|" + "; ".join(reasons),
                # Preserve factor scores for meta-model
                **{f: float(scores.iloc[i].get(f, 0.0)) for f in factor_cols},
            })

    if not out:
        return _empty_signals()

    result = pd.DataFrame(out).sort_values("score", ascending=False)

    # --- Meta-model confidence filter (opt-in) ---
    meta_cfg = cfg.get("meta_model") or {}
    if meta_cfg.get("enabled", False):
        try:
            result = _apply_meta_model_filter(result, meta_cfg)
        except Exception as exc:
            logger.debug("[MF-V2] meta_model filter skipped: %s", exc)

    logger.info(
        "[MF-V2] %d LONG signals from %d symbols "
        "(regime=%s, exposure=%.2f, crash_mult=%.3f, active_factors=%d/%d)",
        len(result), len(latest), regime_label, exposure_mult,
        crash_mult, len(used_factors), len(weights),
    )
    return result


def _apply_meta_model_filter(
    signals: pd.DataFrame,
    meta_cfg: dict[str, Any],
) -> pd.DataFrame:
    """Load classifier, compute confidence, filter / scale signals."""
    model_path = meta_cfg.get("model_path")
    if not model_path or not os.path.exists(model_path):
        raise FileNotFoundError(f"meta_model path missing: {model_path}")

    min_conf = float(meta_cfg.get("min_confidence", 0.55))

    import joblib

    model = joblib.load(model_path)

    feature_cols = meta_cfg.get("feature_cols")
    if not feature_cols:
        feature_cols = [
            c for c in signals.columns
            if c.startswith(("trend_", "mom_", "mr_", "vol_", "vola_", "breadth_",
                             "sector_", "earnings_", "insider_", "news_", "macro_",
                             "intermarket_", "options_", "vix_", "crash_"))
        ]
    if not feature_cols:
        raise ValueError("meta_model: no feature columns available")

    missing = [c for c in feature_cols if c not in signals.columns]
    if missing:
        raise ValueError(f"meta_model: missing columns: {missing}")

    # Guard against silent feature poisoning: fillna(0.0) treats a data-feed
    # gap as a real standardized value, drifting confidence without warning.
    # Predict only on rows with complete features; rows with any NaN feature
    # get meta_confidence=NaN and are filtered by the min_conf gate below.
    feat_frame = signals[feature_cols]
    complete_mask = feat_frame.notna().all(axis=1).to_numpy()
    n_nan_rows = int((~complete_mask).sum())
    if n_nan_rows > 0:
        logger.warning(
            "[multifactor_v2.meta_model] %d/%d rows skipped due to NaN features",
            n_nan_rows,
            len(signals),
        )

    confidence = np.full(len(signals), np.nan, dtype=float)
    if complete_mask.any():
        X = feat_frame.loc[complete_mask].to_numpy()
        proba = model.predict_proba(X)
        if proba.ndim != 2 or proba.shape[1] < 2:
            raise ValueError(f"meta_model: unexpected shape {proba.shape}")
        confidence[complete_mask] = proba[:, 1]

    out = signals.copy()
    out["meta_confidence"] = confidence
    out = out.loc[np.nan_to_num(confidence, nan=-1.0) >= min_conf].copy()
    if out.empty:
        return out
    if "score" in out.columns:
        out["score"] = out["score"].astype(float) * out["meta_confidence"].astype(float)
    return out.reset_index(drop=True)


