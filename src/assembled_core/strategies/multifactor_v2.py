# ATR multipliers per regime
_STOP_ATR_MULT = {"bull": 3.0, "sideways": 2.0, "bear": 1.5, "crisis": 1.0}
_TRAIL_ATR_MULT = {"bull": 2.5, "sideways": 1.8, "bear": 1.2, "crisis": 0.8}
_TP_ATR_MULT = {"bull": 4.0, "sideways": 3.0, "bear": 2.0, "crisis": 1.5}


def _compute_atr(df: pd.DataFrame, symbol: str, window: int = 14) -> float:
    """Compute Average True Range for a symbol."""
    # Callers may pass frames without a timestamp column (e.g. already
    # latest-per-symbol snapshots). Skip the sort when timestamp is absent
    # so the function never raises KeyError on legitimate inputs.
    if "symbol" in df.columns:
        sym_df = df[df["symbol"] == symbol]
    else:
        sym_df = df
    if "timestamp" in sym_df.columns:
        sym_df = sym_df.sort_values("timestamp")
    if len(sym_df) < window + 1:
        return 0.0

    high = pd.to_numeric(sym_df.get("high", sym_df.get("close", pd.Series(dtype=float))), errors="coerce")
    low = pd.to_numeric(sym_df.get("low", sym_df.get("close", pd.Series(dtype=float))), errors="coerce")
    close = pd.to_numeric(sym_df.get("close", pd.Series(dtype=float)), errors="coerce")

    prev_close = close.shift(1)
    tr = pd.concat([
        (high - low).abs(),
        (high - prev_close).abs(),
        (low - prev_close).abs(),
    ], axis=1).max(axis=1)

    atr = tr.iloc[-window:].mean()
    return float(atr) if np.isfinite(atr) else 0.0


def check_exit_signals(
    current_positions: dict,
    prices_latest: pd.DataFrame,
    strategy_cfg: dict | None = None,
) -> pd.DataFrame:
    """ATR-regime adaptive exit signals.

    Uses regime-dependent ATR multipliers for stop-loss, trailing-stop,
    and take-profit. Includes momentum verification to reduce whipsaws.
    Falls back to v1 static exits if ATR computation fails.
    """
    cfg = strategy_cfg or {}
    exit_cfg = cfg.get("exits", {})
    exit_mode = exit_cfg.get("mode", "atr_regime")

    empty = pd.DataFrame(columns=["symbol", "direction", "exit_reason", "exit_qty_pct"])

    if not current_positions or prices_latest is None or prices_latest.empty:
        return empty

    # Fall back to static exits if configured
    if exit_mode == "static":
        from src.assembled_core.strategies.multifactor_v1 import (
            check_exit_signals as _v1_exits,
        )
        return _v1_exits(current_positions, prices_latest, strategy_cfg)

    # Detect regime for ATR multipliers
    regime = _detect_regime(prices_latest, cfg) if "symbol" in prices_latest.columns else "sideways"

    stop_mult = _STOP_ATR_MULT.get(regime, 2.0)
    trail_mult = _TRAIL_ATR_MULT.get(regime, 1.8)
    tp_mult = _TP_ATR_MULT.get(regime, 3.0)

    # Override from config if provided
    if "stop_atr_mult_by_regime" in exit_cfg:
        stop_mult = exit_cfg["stop_atr_mult_by_regime"].get(regime, stop_mult)
    if "trail_atr_mult_by_regime" in exit_cfg:
        trail_mult = exit_cfg["trail_atr_mult_by_regime"].get(regime, trail_mult)
    if "tp_atr_mult_by_regime" in exit_cfg:
        tp_mult = exit_cfg["tp_atr_mult_by_regime"].get(regime, tp_mult)

    atr_window = int(exit_cfg.get("atr_window", 14))
    momentum_verify = exit_cfg.get("momentum_verification", True)
    time_stop_days = int(exit_cfg.get("time_stop_days", 30))
    time_stop_min_return = float(exit_cfg.get("time_stop_min_return", 0.03))

    price_map = {}
    if "symbol" in prices_latest.columns and "close" in prices_latest.columns:
        price_map = dict(zip(prices_latest["symbol"].values, prices_latest["close"].values))

    exits = []
    for sym, pos in current_positions.items():
        qty = float(pos.get("qty", 0))
        if qty <= 0:
            continue
        avg_price = float(pos.get("avg_price", 0))
        hwm = float(pos.get("hwm", avg_price))
        if avg_price <= 0:
            continue

        current_price = float(price_map.get(sym, 0))
        if current_price <= 0:
            continue

        if current_price > hwm:
            hwm = current_price

        atr = _compute_atr(prices_latest, sym, atr_window)
        if atr <= 0:
            # Fallback to percentage-based stops
            atr = avg_price * 0.02  # ~2% as proxy

        # --- Stop-loss (ATR-based) ---
        stop_price = avg_price - stop_mult * atr
        if current_price <= stop_price:
            # Momentum verification: skip exit if RSI < 30 and EMA trending up
            if momentum_verify and _momentum_intact(prices_latest, sym):
                logger.debug("[MF-V2] %s: stop hit but momentum intact, holding", sym)
                continue
            exits.append({
                "symbol": sym,
                "direction": "FLAT",
                "exit_reason": f"stop_atr_{regime} ({current_price:.2f} <= {stop_price:.2f})",
                "exit_qty_pct": 1.0,
            })
            continue

        # --- Trailing stop (ATR-based on HWM) ---
        if hwm > avg_price:
            trail_price = hwm - trail_mult * atr
            if current_price <= trail_price:
                exits.append({
                    "symbol": sym,
                    "direction": "FLAT",
                    "exit_reason": f"trailing_atr_{regime} ({current_price:.2f} <= {trail_price:.2f}, hwm={hwm:.2f})",
                    "exit_qty_pct": 1.0,
                })
                continue

        # --- Take-profit (partial, ATR-based) ---
        tp_price = avg_price + tp_mult * atr
        if current_price >= tp_price:
            exits.append({
                "symbol": sym,
                "direction": "FLAT",
                "exit_reason": f"take_profit_atr_{regime} ({current_price:.2f} >= {tp_price:.2f})",
                "exit_qty_pct": 0.5,
            })
            continue

        # --- Time stop (zombie killer) ---
        days_held = int(pos.get("days_held", 0))
        if days_held > time_stop_days:
            return_pct = (current_price - avg_price) / avg_price if avg_price > 0 else 0.0
            if return_pct < time_stop_min_return:
                exits.append({
                    "symbol": sym,
                    "direction": "FLAT",
                    "exit_reason": f"time_stop ({days_held}d, return={return_pct:.2%} < {time_stop_min_return:.2%})",
                    "exit_qty_pct": 1.0,
                })
                continue

    if not exits:
        return empty
    return pd.DataFrame(exits)


def _momentum_intact(prices_latest: pd.DataFrame, symbol: str) -> bool:
    """Check if momentum is still intact (whipsaw protection).

    Returns True if RSI < 30 AND short-term EMA is above long-term EMA,
    suggesting the stop hit is a dip-in-uptrend rather than a reversal.
    """
    try:
        if "symbol" not in prices_latest.columns:
            return False
        sym_df = prices_latest[prices_latest["symbol"] == symbol]
        if sym_df.empty:
            return False

        row = sym_df.iloc[-1]
        rsi = float(row.get("ta_rsi_14_v1", 50.0))
        if rsi >= 30:
            return False

        # Check EMA trend
        ema_spread = float(row.get("trend_ema_spread", 0.0))
        if ema_spread <= 0:
            return False

        return True
    except Exception:
        return False


