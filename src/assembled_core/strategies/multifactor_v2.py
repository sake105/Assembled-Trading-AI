_REGIME_WEIGHTS_CACHE: dict[str, dict[str, float]] | None = None


def _load_regime_weights(cfg: dict[str, Any]) -> dict[str, dict[str, float]] | None:
    """Load regime-conditional factor weights from JSON file.

    Returns None if the file is missing or unparseable (defensive).
    """
    global _REGIME_WEIGHTS_CACHE  # noqa: PLW0603
    if _REGIME_WEIGHTS_CACHE is not None:
        return _REGIME_WEIGHTS_CACHE

    path = cfg.get("regime_weights_path", "configs/factor_weights_by_regime.json")
    if not os.path.isfile(path):
        logger.debug("[MF-V2] Regime weights file not found: %s", path)
        return None
    try:
        with open(path) as fh:
            data = json.load(fh)
        # Validate: must have at least one regime key with a dict value
        regimes = {k: v for k, v in data.items() if isinstance(v, dict) and not k.startswith("_")}
        if not regimes:
            return None
        _REGIME_WEIGHTS_CACHE = regimes
        logger.info("[MF-V2] Loaded regime weights for regimes: %s", list(regimes.keys()))
        return regimes
    except Exception as exc:
        logger.debug("[MF-V2] Failed to load regime weights: %s", exc)
        return None


def _get_weights_for_regime(
    regime_label: str,
    cfg: dict[str, Any],
) -> dict[str, float]:
    """Return factor weights for the given regime, or defaults."""
    regime_weights = _load_regime_weights(cfg)
    if regime_weights and regime_label in regime_weights:
        return regime_weights[regime_label]
    return DEFAULT_V2_WEIGHTS


