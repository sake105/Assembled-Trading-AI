def _detect_regime(df: pd.DataFrame, cfg: dict[str, Any]) -> str:
    """Detect current market regime label."""
    # Try pre-trained HMM model first (MultiFeatureRegimeHMM, 2D: return+vol_20d)
    try:
        from pathlib import Path as _Path
        from src.assembled_core.ml.regime_hmm import MultiFeatureRegimeHMM

        _hmm_path = (
            _Path(__file__).parents[3] / "models" / "regime_hmm_4state_spy.joblib"
        )
        if _hmm_path.exists() and "close" in df.columns and "timestamp" in df.columns:
            _hmm_cache_key = (str(_hmm_path), _hmm_path.stat().st_mtime)
            _hmm = _HMM_MODEL_CACHE.get(_hmm_cache_key)
            if _hmm is None:
                _hmm = MultiFeatureRegimeHMM.load(_hmm_path)
                _HMM_MODEL_CACHE.set(_hmm_cache_key, _hmm)
            if "symbol" in df.columns:
                _px = df.pivot_table(
                    index="timestamp", columns="symbol", values="close", aggfunc="last"
                )
                _mkt = _px.mean(axis=1)
            else:
                _mkt = df.set_index("timestamp")["close"]
            _mkt = _mkt.sort_index().dropna()
            _log_ret = np.log((_mkt / _mkt.shift(1)).clip(lower=1e-10)).dropna()
            _vol_20d = _log_ret.rolling(20, min_periods=20).std().dropna()
            _log_ret = _log_ret.loc[_vol_20d.index]
            if len(_log_ret) >= 20:
                _feat = pd.DataFrame(
                    {"daily_return": _log_ret.values, "realized_vol": _vol_20d.values},
                    index=_log_ret.index,
                )
                _regimes = _hmm.predict_regime(_feat)
                if len(_regimes) > 0:
                    return str(_regimes.iloc[-1])
    except Exception as _exc:
        logger.debug("[multifactor_v2] HMM regime prediction failed: %s", _exc)

    try:
        from src.assembled_core.risk.regime_models import build_regime_state

        regime_df = build_regime_state(df)
        if regime_df is not None and not regime_df.empty:
            label = str(regime_df.iloc[-1].get("regime_label", "neutral")).lower()
            return label
    except Exception as _exc:
        logger.debug("[multifactor_v2] build_regime_state failed: %s", _exc)

    # Fallback: breadth-based
    breadth = _compute_breadth_score(df)
    if breadth < -0.4:
        return "bear"
    if breadth < -0.1:
        return "sideways"
    if breadth > 0.3:
        return "bull"
    return "sideways"


